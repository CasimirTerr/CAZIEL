"""Build the website's data from the real engine.

1. Runs `caziel fix` on examples/harbor-fleet into examples/harbor-fleet-hardened
2. Scans both and writes docs/data/before.json and docs/data/after.json

The website never computes its own numbers. Everything it shows comes from these files.

    python scripts/build_site_data.py           # rebuild
    python scripts/build_site_data.py --check   # exit 1 if committed output is stale (CI)
"""

from __future__ import annotations

import filecmp
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from caziel import analysis, cloud, live, policy, report  # noqa: E402

SRC = ROOT / "examples" / "harbor-fleet"
HARD = ROOT / "examples" / "harbor-fleet-hardened"
DATA = ROOT / "docs" / "data"


def build(hardened: Path, data: Path) -> None:
    plan, before, _after = policy.fix(SRC, hardened)
    data.mkdir(parents=True, exist_ok=True)
    b = report.to_dict(before)
    a = report.to_dict(analysis.analyze(cloud.load(hardened)))
    a["changes"] = [c.__dict__ for c in plan.changes]
    a["manual"] = plan.manual
    # The live demo: one recorded shift, classified by `caziel watch` against both fleets.
    traffic = SRC / "traffic" / "shift.jsonl"
    with traffic.open() as f:
        events = list(live.read_events(f))
    stream = {
        "events": events,
        "before": [v.to_dict() for v in live.Watcher(before.fleet).watch(events)],
        "after": [v.to_dict() for v in live.Watcher(cloud.load(hardened)).watch(events)],
    }
    (data / "live.json").write_text(json.dumps(stream, indent=1) + "\n")
    for name, payload in (("before.json", b), ("after.json", a)):
        (data / name).write_text(json.dumps(payload, indent=2) + "\n")
    # Same data as a script, so docs/index.html also works when opened straight from disk.
    bundle = json.dumps({"before": b, "after": a, "live": stream}, separators=(",", ":"))
    header = "// Generated by scripts/build_site_data.py\n"
    (data / "caziel-data.js").write_text(f"{header}window.CAZIEL_DATA = {bundle};\n")


def same_tree(x: Path, y: Path) -> bool:
    cmp = filecmp.dircmp(x, y)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    return all(same_tree(x / d, y / d) for d in cmp.common_dirs)


def main() -> int:
    if "--check" in sys.argv:
        with tempfile.TemporaryDirectory() as tmp:
            t = Path(tmp)
            build(t / "hardened", t / "data")
            ok = same_tree(t / "hardened", HARD) and same_tree(t / "data", DATA)
        if not ok:
            print("Generated examples or site data are stale. Run: python scripts/build_site_data.py", file=sys.stderr)
            return 1
        return 0
    build(HARD, DATA)
    print(f"wrote {HARD.relative_to(ROOT)} and {DATA.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
